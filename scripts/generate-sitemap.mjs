#!/usr/bin/env node
/**
 * Regenerates public/sitemap.xml and public/robots.txt from the REAL project files and the
 * site URL in src/config/site.ts — so adding a project (or changing the domain) never needs a
 * manual sitemap edit. Runs automatically before `npm run build` (see "prebuild" in package.json).
 * Draft projects (draft: true) are left out, exactly like they are hidden on the live site.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const siteSource = readFileSync(join(root, "src/config/site.ts"), "utf8");
const base = (siteSource.match(/^\s*url:\s*"(https?:\/\/[^"]+)"/m)?.[1] ?? "").replace(/\/+$/, "");
if (!base) {
  console.error('[sitemap] Could not find `url: "https://…"` in src/config/site.ts');
  process.exit(1);
}

const projectsDir = join(root, "src/content/projects");
const projects = [];
for (const file of readdirSync(projectsDir).sort()) {
  if (!file.endsWith(".ts") || file === "index.ts" || file.startsWith("_")) continue;
  const text = readFileSync(join(projectsDir, file), "utf8");
  const slug = text.match(/^\s*slug:\s*"([^"]*)"/m)?.[1];
  const draft = /^\s*draft:\s*true/m.test(text);
  const featured = /^\s*featured:\s*true/m.test(text);
  if (!slug || !SLUG.test(slug)) {
    console.warn(`[sitemap] skipped ${file}: slug "${slug ?? ""}" must be lowercase-with-dashes.`);
    continue;
  }
  if (draft) continue;
  projects.push({ slug, featured });
}

const pages = [
  ["/", "1.0"],
  ["/projects", "0.9"],
  ...projects.map((p) => [`/projects/${p.slug}`, p.featured ? "0.8" : "0.6"]),
  ["/experience", "0.8"],
  ["/stack", "0.7"],
  ["/about", "0.7"],
  ["/contact", "0.6"],
];

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/generate-sitemap.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(([path, priority]) => `  <url><loc>${base}${path === "/" ? "/" : path}</loc><priority>${priority}</priority></url>`).join("\n")}
</urlset>
`;
writeFileSync(join(root, "public/sitemap.xml"), xml);
writeFileSync(join(root, "public/robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`);
console.log(`[sitemap] ${pages.length} URLs for ${base} (${projects.length} published projects)`);
